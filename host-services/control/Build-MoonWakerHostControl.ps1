#requires -Version 5.1
[CmdletBinding()]
param([string]$OutputDirectory = (Join-Path $PSScriptRoot "dist"))
$ErrorActionPreference = "Stop"
New-Item -ItemType Directory -Path $OutputDirectory -Force | Out-Null
$compiler = "C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe"
if (-not (Test-Path -LiteralPath $compiler)) { $compiler = "C:\Windows\Microsoft.NET\Framework\v4.0.30319\csc.exe" }
if (-not (Test-Path -LiteralPath $compiler)) { throw ".NET Framework C# compiler was not found." }
$output = Join-Path $OutputDirectory "MoonWakerHostControl.exe"
$configuratorOutput = Join-Path $OutputDirectory "MoonWakerHostConfigurator.exe"

# Generated by store-assets\Build-MoonWakerIcons.ps1; also the tray icon (MoonWaker.Icon.ico).
$iconPath = Join-Path $PSScriptRoot "moonwaker-host-control.ico"
$wpf = @("/lib:$(Join-Path (Split-Path -Parent $compiler) 'WPF')", "/reference:PresentationFramework.dll",
    "/reference:PresentationCore.dll", "/reference:WindowsBase.dll", "/reference:System.Xaml.dll")
$compilerArguments = @(
    "/nologo", "/target:winexe", "/optimize+", "/out:$output", "/win32icon:$iconPath",
    "/resource:$iconPath,MoonWaker.Icon.ico",
    "/win32manifest:$(Join-Path $PSScriptRoot 'MoonWakerHostControl.manifest')",
    "/reference:System.dll", "/reference:System.Core.dll", "/reference:System.Drawing.dll",
    "/reference:System.Windows.Forms.dll", "/reference:System.Web.Extensions.dll",
    "/reference:System.Security.dll", "/reference:System.ServiceProcess.dll",
    "/reference:System.Management.dll",
    "/reference:System.IO.Compression.dll", "/reference:System.IO.Compression.FileSystem.dll") + $wpf + @(
    (Join-Path $PSScriptRoot "MoonWakerHostControl.cs"),
    (Join-Path $PSScriptRoot "HostControlWindow.cs"),
    (Join-Path $PSScriptRoot "HostControlUi.cs"),
    (Join-Path $PSScriptRoot "HostControlBackend.cs"),
    (Join-Path $PSScriptRoot "HostChanges.cs"))
& $compiler @compilerArguments
if ($LASTEXITCODE -ne 0 -or -not (Test-Path -LiteralPath $output)) { throw "MoonWaker Host Control compilation failed." }

# The elevated helper shares the window style (HostControlUi.cs) and the change channel
# (HostChanges.cs) with Host Control.
$configuratorArguments = @(
    "/nologo", "/target:winexe", "/platform:x64", "/optimize+",
    "/main:MoonWaker.HostConfigurator.Program", "/out:$configuratorOutput",
    "/win32icon:$iconPath",
    "/win32manifest:$(Join-Path $PSScriptRoot 'MoonWakerHostConfigurator.manifest')",
    "/reference:System.dll", "/reference:System.Core.dll", "/reference:System.Web.Extensions.dll",
    "/reference:System.Management.dll", "/reference:System.Security.dll") + $wpf + @(
    (Join-Path $PSScriptRoot "MoonWakerHostConfigurator.cs"),
    (Join-Path $PSScriptRoot "ConfiguratorChanges.cs"),
    (Join-Path $PSScriptRoot "HostChanges.cs"),
    (Join-Path $PSScriptRoot "HostControlUi.cs"))
& $compiler @configuratorArguments
if ($LASTEXITCODE -ne 0 -or -not (Test-Path -LiteralPath $configuratorOutput)) {
    throw "MoonWaker Host Configurator compilation failed."
}

Get-Item -LiteralPath $output, $configuratorOutput
